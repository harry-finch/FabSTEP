//! Documents placés en millimètres, sans fusion ni export partiel.
use crate::{
    convert_analysis, precision_diagnostic, triangle_model, ConversionReport, ProcessingSettings,
};
use fabstep_cad::{combine_steps, validate_sources_separated, CadReport, StepPart};
use fabstep_core::{
    analyze_mesh_bodies, read_stl_mesh, Analysis, Diagnostic, FabError, InputUnit, Mesh, Options,
    Severity,
};
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum InputFormat {
    #[serde(rename = "stl")]
    Stl,
    #[serde(rename = "3mf")]
    ThreeMf,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum UnitOrigin {
    Selected,
    Declared,
    Default,
}

#[derive(Debug, Clone, Serialize)]
pub struct DocumentSource {
    pub format: InputFormat,
    pub unit: String,
    pub unit_origin: UnitOrigin,
}

#[derive(Debug, Clone, Default, Serialize)]
pub struct BodyProvenance {
    /// True only for a fallback generated by FabSTEP, never for a source name.
    pub generated_name: bool,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub model_path: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub object_id: Option<u32>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub build_item: Option<usize>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub instance_path: Option<Vec<usize>>,
    pub component_index: usize,
}

#[derive(Debug, Clone, Serialize)]
pub struct PreviewBody {
    pub id: String,
    pub name: String,
    pub provenance: BodyProvenance,
    pub mesh: Mesh,
}

/// Lecture bornée uniquement : les maillages de cet aperçu ne sont pas encore
/// validés pour la CAO et n'autorisent jamais un export.
#[derive(Debug, Clone, Serialize)]
pub struct DocumentPreview {
    pub source: DocumentSource,
    pub bodies: Vec<PreviewBody>,
    pub diagnostics: Vec<Diagnostic>,
}

#[derive(Debug, Clone, Serialize)]
pub struct AnalyzedBody {
    pub id: String,
    pub name: String,
    pub provenance: BodyProvenance,
    pub analysis: Analysis,
}

#[derive(Debug, Clone, Serialize)]
pub struct DocumentAnalysis {
    pub settings: ProcessingSettings,
    pub source: DocumentSource,
    pub bodies: Vec<AnalyzedBody>,
    pub diagnostics: Vec<Diagnostic>,
}

#[derive(Debug, Clone, Serialize)]
pub struct BodyReport {
    pub id: String,
    pub name: String,
    pub provenance: BodyProvenance,
    #[serde(flatten)]
    pub conversion: ConversionReport,
}

#[derive(Debug, Clone, Serialize)]
pub struct DocumentReport {
    pub settings: ProcessingSettings,
    pub source: DocumentSource,
    pub bodies: Vec<BodyReport>,
    pub cad: CadReport,
    pub diagnostics: Vec<Diagnostic>,
}

pub struct DocumentConversion {
    pub report: DocumentReport,
    pub step_bytes: Vec<u8>,
}

pub fn preview_document(
    bytes: &[u8],
    format: InputFormat,
    options: &Options,
) -> Result<DocumentPreview, FabError> {
    match format {
        InputFormat::Stl => Ok(DocumentPreview {
            source: DocumentSource {
                format,
                unit: match options.input_unit {
                    InputUnit::Mm => "mm",
                    InputUnit::Inch => "inch",
                }
                .into(),
                unit_origin: UnitOrigin::Selected,
            },
            bodies: vec![PreviewBody {
                id: "stl".into(),
                name: "Corps STL".into(),
                provenance: BodyProvenance::default(),
                mesh: read_stl_mesh(bytes, options.input_unit)?,
            }],
            diagnostics: Vec::new(),
        }),
        InputFormat::ThreeMf => {
            let doc = fabstep_import::import_3mf(bytes)?;
            let source = DocumentSource {
                format,
                unit: doc.unit,
                unit_origin: match doc.unit_origin {
                    fabstep_import::UnitOrigin::Declared => UnitOrigin::Declared,
                    fabstep_import::UnitOrigin::Default => UnitOrigin::Default,
                },
            };
            let bodies = doc
                .bodies
                .into_iter()
                .map(|b| {
                    let s = b.source;
                    let mut id = format!("3mf/build/{}", s.build_item);
                    for index in &s.instance_path {
                        id.push_str(&format!("/component-ref/{index}"));
                    }
                    let fallback = format!("Objet {} · {}", s.object_id, s.build_item + 1);
                    let source_name = s.name.filter(|n| !n.trim().is_empty());
                    let generated_name = source_name.is_none();
                    PreviewBody {
                        id,
                        name: source_name.unwrap_or(fallback),
                        provenance: BodyProvenance {
                            generated_name,
                            model_path: Some(s.model_path),
                            object_id: Some(s.object_id),
                            build_item: Some(s.build_item),
                            instance_path: Some(s.instance_path),
                            component_index: 0,
                        },
                        mesh: b.mesh,
                    }
                })
                .collect();
            Ok(DocumentPreview {
                source,
                bodies,
                diagnostics: doc.diagnostics,
            })
        }
    }
}

/// Analyse topologique de chaque composante. La séparation spatiale des corps
/// et leur validité BRep restent à vérifier par `convert_document`.
pub fn analyze_document(
    bytes: &[u8],
    format: InputFormat,
    options: &Options,
) -> Result<DocumentAnalysis, FabError> {
    let preview = preview_document(bytes, format, options)?;
    let mut bodies = Vec::new();
    for body in preview.bodies {
        let analyses = analyze_mesh_bodies(&body.mesh, options)
            .map_err(|e| body_error(e, &body.id, &body.name))?;
        let count = analyses.len();
        if bodies.len() + count > 32 {
            return Err(FabError::new(
                "input.too_many_bodies",
                "Document limité à 32 corps après séparation des composantes.",
            ));
        }
        for (index, analysis) in analyses.into_iter().enumerate() {
            let mut provenance = body.provenance.clone();
            provenance.component_index = index;
            let name = if count == 1 {
                body.name.clone()
            } else {
                format!("{} · {}", body.name, index + 1)
            };
            bodies.push(AnalyzedBody {
                id: format!("{}/component/{index}", body.id),
                name,
                provenance,
                analysis,
            });
        }
    }
    let mut diagnostics = preview.diagnostics;
    if let Some(diagnostic) = precision_diagnostic(options) {
        diagnostics.push(diagnostic);
    }
    if bodies.len() > 1 {
        diagnostics.push(Diagnostic { code: "document.separate_bodies".into(), severity: Severity::Info, message: "Chaque composante sera conservée comme solide distinct ; séparation spatiale à valider par le noyau CAO.".into(), count: bodies.len() });
    }
    Ok(DocumentAnalysis {
        settings: ProcessingSettings::from(options),
        source: preview.source,
        bodies,
        diagnostics,
    })
}

pub fn convert_document(
    bytes: &[u8],
    format: InputFormat,
    options: &Options,
) -> Result<DocumentConversion, FabError> {
    let document = analyze_document(bytes, format, options)?;
    if document.bodies.len() > 1 {
        // Une reconstruction ne doit pas dissimuler un contact ou recouvrement
        // de la source. La séparation est aussi contrôlée sur le STEP final.
        let models = document
            .bodies
            .iter()
            .map(|b| triangle_model(&b.analysis.mesh))
            .collect::<Vec<_>>();
        validate_sources_separated(&models)?;
    }
    let mut bodies = Vec::with_capacity(document.bodies.len());
    let mut steps = Vec::with_capacity(document.bodies.len());
    let mut step_size = 0usize;
    for body in document.bodies {
        let conversion = convert_analysis(body.analysis, options)
            .map_err(|e| body_error(e, &body.id, &body.name))?;
        step_size = step_size.saturating_add(conversion.step_bytes.len());
        if step_size > 128 * 1024 * 1024 {
            return Err(FabError::new(
                "cad.step_document_too_large",
                "La somme des corps STEP dépasse 128 Mio.",
            ));
        }
        steps.push(conversion.step_bytes);
        bodies.push(BodyReport {
            id: body.id,
            name: body.name,
            provenance: body.provenance,
            conversion: conversion.report,
        });
    }
    let mut names_adapted = 0;
    let (step_bytes, cad) = if bodies.len() == 1 && format == InputFormat::Stl {
        (
            steps.pop().expect("one converted body"),
            bodies[0].conversion.cad.clone(),
        )
    } else {
        let names = bodies
            .iter()
            .map(|b| product_name(&b.name, "FabSTEP"))
            .collect::<Vec<_>>();
        names_adapted = names
            .iter()
            .zip(&bodies)
            .filter(|(name, body)| **name != body.name)
            .count();
        let parts = steps
            .iter()
            .zip(&names)
            .map(|(bytes, name)| StepPart { bytes, name })
            .collect::<Vec<_>>();
        let result = combine_steps(&parts)?;
        (result.bytes, result.report)
    };
    let mut diagnostics = document.diagnostics;
    if names_adapted > 0 {
        diagnostics.push(Diagnostic { code: "document.product_names_adapted".into(), severity: Severity::Info, message: "Des noms de produit STEP ont été raccourcis ou normalisés pour le noyau CAO ; les noms source restent dans le rapport.".into(), count: names_adapted });
    }
    for d in &mut diagnostics {
        if d.code == "document.separate_bodies" {
            d.message =
                "Corps distincts, séparation spatiale vérifiée et STEP réimporté ; aucune fusion."
                    .into();
        }
    }
    Ok(DocumentConversion {
        report: DocumentReport {
            settings: document.settings,
            source: document.source,
            bodies,
            cad,
            diagnostics,
        },
        step_bytes,
    })
}

fn body_error(e: FabError, id: &str, name: &str) -> FabError {
    e.with_body(id, name)
}

fn product_name(name: &str, fallback: &str) -> String {
    let mut clean: String = name
        .chars()
        .filter(|c| !c.is_control())
        .map(|c| if c == '\\' { '/' } else { c })
        .collect();
    clean = clean.trim().to_owned();
    while clean.len() > 60 {
        clean.pop();
    }
    if clean.is_empty() {
        fallback.into()
    } else {
        clean
    }
}
