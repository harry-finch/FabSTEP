    #[test]
    fn rounded_face_limit_reports_the_count_separately_from_invalid_attribution() {
        let options = Options {
            reconstruction: ReconstructionMode::Auto,
            ..Options::default()
        };
        let analysis = fabstep_core::analyze_stl(
            include_bytes!("../../../fixtures/m4_chamfered_cylinder.stl"),
            &options,
        )
        .unwrap();
        let mut recognized = fabstep_core::recognize_automatic(&analysis, &options).unwrap();
        let source = BodySourceTriangles {
            preview_body_id: "source".into(),
            analysis_to_source_triangles: (0..analysis.mesh.triangles.len()).collect(),
            planar_triangle_faces: Vec::new(),
        };
        let mut faces = Vec::new();
        let count = rounded_source_faces("body", &source, &recognized, Some(&mut faces)).unwrap();
        assert_eq!(faces.len(), count);
        assert_eq!(
            rounded_source_faces("body", &source, &recognized, None).unwrap(),
            count
        );
        let mut invalid_source = source.clone();
        invalid_source.analysis_to_source_triangles.pop();
        let invalid = rounded_source_faces("body", &invalid_source, &recognized, None).unwrap_err();
        assert_eq!(invalid.code, "step.invalid_source_provenance");
        assert!(invalid.message.contains("incohérente"));
        // Dropping the lookup must still reject a native face without any owner.
        let owner = recognized.triangle_faces[0];
        let replacement = *recognized
            .triangle_faces
            .iter()
            .find(|&&other| other != owner)
            .unwrap();
        let mut incomplete = recognized.clone();
        for slot in &mut incomplete.triangle_faces {
            if *slot == owner {
                *slot = replacement;
            }
        }
        for destination in [None, Some(&mut Vec::new())] {
            let error =
                rounded_source_faces("body", &source, &incomplete, destination).unwrap_err();
            assert_eq!(error.code, "step.invalid_source_provenance");
        }
        let planes = &mut recognized.model.revolved.mixed.planes;
        let other_faces = count - planes.len();
        planes.resize(100_001 - other_faces, planes[0].clone());
        let limit = rounded_source_faces("body", &source, &recognized, None).unwrap_err();
        assert_eq!(limit.code, "step.invalid_source_provenance");
        assert!(limit.message.contains("100001 faces"));
        assert!(limit.message.contains("limité à 100000"));
        assert!(!limit.message.contains("incohérente"));
    }

    #[test]
    fn guidance_reuses_only_its_immutable_results_resolved_correspondence() {
        use std::sync::atomic::Ordering;
        let options = Options::default();
        let converted = convert_document_with_provenance(
            include_bytes!("../../../fixtures/cube.stl"),
            InputFormat::Stl,
            &options,
        )
        .unwrap();
        assert!(converted.step.source_correspondence.get().is_none());
        let inspection = converted.step.result_faces().unwrap();
        assert_eq!(inspection.source_correspondence.status, "exact");
        assert_eq!(converted.step.result_inspections.load(Ordering::Relaxed), 1);
        let cached = converted.step.resolved_source_correspondence().unwrap();
        assert_eq!(cached.faces, inspection.source_correspondence.faces);
        assert!(std::ptr::eq(
            cached,
            converted.step.resolved_source_correspondence().unwrap()
        ));
        // A cube cap cannot become a cylinder. Even the rejected guided attempt
        // reaches recognition using the cached table, with no second inspection.
        assert_eq!(
            converted.step.guided_cylinder(&[0]).err().unwrap().code,
            "guidance.cylinder_unproven"
        );
        assert_eq!(converted.step.result_inspections.load(Ordering::Relaxed), 1);
        let rebuilt = converted.step.recompute_guidance().unwrap();
        assert!(rebuilt.step.source_correspondence.get().is_none());
        assert_eq!(rebuilt.step.result_inspections.load(Ordering::Relaxed), 0);
        // Recovered bytes alone cannot inherit the original object's sidecar.
        let untracked = DocumentStep::untracked(converted.step.bytes().to_vec());
        assert_eq!(
            untracked.resolved_source_correspondence().unwrap().status,
            "unavailable"
        );
        assert_eq!(untracked.result_inspections.load(Ordering::Relaxed), 1);
        assert_eq!(
            untracked.resolved_source_correspondence().unwrap().status,
            "unavailable"
        );
        assert_eq!(untracked.result_inspections.load(Ordering::Relaxed), 1);
    }

